/* ============================================================
   1. CAT_MAESTRO  (catalogo de catalogos)
   ============================================================ */

CREATE TABLE cat_maestro (
    id_mae NUMBER(5)
        GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT pk_cat_maestro PRIMARY KEY
            USING INDEX TABLESPACE TS_MD_INDICES,

    nom_tabla VARCHAR2(100) NOT NULL,

    sigla_tabla VARCHAR2(10) NOT NULL,

    activo_tabla CHAR(1) DEFAULT 'S' NOT NULL,

    CONSTRAINT uq_cat_maestro_sigla
        UNIQUE (sigla_tabla)
        USING INDEX TABLESPACE TS_MD_INDICES,

    CONSTRAINT ck_cat_maestro_activo
        CHECK (activo_tabla IN ('S', 'N'))
)
TABLESPACE TS_MD_DATOS;


/* ============================================================
   2. CAT_DETALLE  (valores de cada catalogo)
   ============================================================ */

CREATE TABLE cat_detalle (
    id NUMBER(5)
        GENERATED BY DEFAULT AS IDENTITY
