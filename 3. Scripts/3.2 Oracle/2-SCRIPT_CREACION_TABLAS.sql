/* ============================================================
   13. RUTA_REPARTO
   ============================================================ */

CREATE TABLE ruta_reparto (
    ruta_id NUMBER(10)
        GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT pk_ruta_reparto PRIMARY KEY
            USING INDEX TABLESPACE TS_MD_INDICES,

    codigo_ruta VARCHAR2(30) NOT NULL,

    centro_acopio_id NUMBER(10) NOT NULL,

    vehiculo_id NUMBER(10) NOT NULL,

    transportista_id NUMBER(10) NOT NULL,

    fecha_hora_salida TIMESTAMP NOT NULL,

    fecha_hora_retorno_estimada TIMESTAMP,

    distancia_estimada_km NUMBER(10,2),

    estado_id NUMBER(5) NOT NULL,

    observaciones VARCHAR2(300),

    CONSTRAINT uq_ruta_codigo
        UNIQUE (codigo_ruta)
        USING INDEX TABLESPACE TS_MD_INDICES,

    CONSTRAINT fk_ruta_centro
        FOREIGN KEY (centro_acopio_id)
        REFERENCES centro_acopio(centro_acopio_id),

    CONSTRAINT fk_ruta_vehiculo
        FOREIGN KEY (vehiculo_id)
        REFERENCES vehiculo(vehiculo_id),

    CONSTRAINT fk_ruta_transportista
        FOREIGN KEY (transportista_id)
        REFERENCES transportista(transportista_id),

    CONSTRAINT fk_ruta_estado
        FOREIGN KEY (estado_id)
        REFERENCES cat_detalle(id),

    CONSTRAINT ck_ruta_distancia
        CHECK (
            distancia_estimada_km IS NULL
            OR distancia_estimada_km >= 0
        ),

    CONSTRAINT ck_ruta_retorno
        CHECK (
            fecha_hora_retorno_estimada IS NULL
            OR fecha_hora_retorno_estimada >= fecha_hora_salida
        )
)
TABLESPACE TS_MD_DATOS;


