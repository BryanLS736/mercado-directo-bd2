        FOREIGN KEY (id_mae)
        REFERENCES cat_maestro(id_mae),

    CONSTRAINT uq_cat_detalle_mae_nombre
        UNIQUE (id_mae, nombre)
        USING INDEX TABLESPACE TS_MD_INDICES,

    CONSTRAINT ck_cat_detalle_estado
        CHECK (estado IN ('S', 'N'))
)
TABLESPACE TS_MD_DATOS;


