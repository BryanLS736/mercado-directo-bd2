            USING INDEX TABLESPACE TS_MD_INDICES,

    id_mae NUMBER(5) NOT NULL,

    nombre VARCHAR2(100) NOT NULL,

    valor VARCHAR2(20),

    estado CHAR(1) DEFAULT 'S' NOT NULL,

